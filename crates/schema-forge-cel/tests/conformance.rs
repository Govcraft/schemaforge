//! CEL conformance oracle (#90).
//!
//! Runs the engine against the vendored `google/cel-spec` `simple` corpus,
//! filtered to the SchemaForge-relevant subset (proto-message sections are
//! excluded by design — see [`EXCLUDED`]). Reports pass/fail by feature and
//! enforces a ratcheting baseline: each engine stage (#107/#108/#109) raises
//! [`MIN_PASS_BASELINE`] as it turns sections green.
//!
//! The corpus is pre-encoded to binary by `build.rs`; this harness only decodes
//! and runs it. Generated protobuf types are confined to the `proto` module
//! below and never touch the engine's public API.

#[allow(clippy::all, clippy::pedantic, clippy::nursery, dead_code, unused)]
mod proto {
    // Machine-generated by prost-build (build.rs); not hand-editable, so pedantic
    // lints are scoped out of it here rather than suppressed in engine logic.
    include!(concat!(env!("OUT_DIR"), "/_includes.rs"));
}

use std::collections::BTreeMap;

